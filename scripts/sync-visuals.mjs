import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=fs.readFileSync(path.join(root,'shared/visuals/cinematic.frag'),'utf8');
if(source.includes('`')||source.includes('${'))throw new Error('GLSL cannot contain template interpolation');
const generated='// Generated by scripts/sync-visuals.mjs from shared/visuals/cinematic.frag.\nexport const cinematicFragmentShader = `'+source+'`;\n';
const target=path.join(root,'apps/mobile/src/visuals/cinematic.generated.ts');
if(process.argv.includes('--check')){
 if(fs.readFileSync(target,'utf8')!==generated)throw new Error('Shared mobile shader is stale. Run node scripts/sync-visuals.mjs');
}else fs.writeFileSync(target,generated);
console.log('AURALIS_SHARED_SHADER_OK');
